def get_registration_dataframe():
    """Return a pandas DataFrame of NC county voter registration."""
    import pandas as pd
    columns = ["county_name", "reg_dem", "reg_rep", "reg_unaf", "reg_lib", "reg_total"]
    df = pd.DataFrame(NC_REGISTRATION, columns=columns)
    df["reg_dem_share"] = df["reg_dem"] / df["reg_total"]
    df["reg_rep_share"] = df["reg_rep"] / df["reg_total"]
    df["reg_unaf_share"] = df["reg_unaf"] / df["reg_total"]
    return df
