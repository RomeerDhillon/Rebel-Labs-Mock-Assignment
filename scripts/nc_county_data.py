COLUMNS = [
    "county_fips", "county_name", "total_pop", "pct_white", "pct_black",
    "pct_hispanic", "pct_college", "median_age", "median_household_income",
    "land_area_sqmi",
]


def get_demographics_dataframe():
    """Return a pandas DataFrame of NC county demographics."""
    import pandas as pd
    df = pd.DataFrame(NC_COUNTY_DEMOGRAPHICS, columns=COLUMNS)
    df["pop_density"] = df["total_pop"] / df["land_area_sqmi"]

    # Classify urban/rural using NC Rural Center thresholds
    def classify(density):
        if density >= 750:
            return "urban"
        elif density >= 250:
            return "suburban"
        else:
            return "rural"

    df["urban_rural"] = df["pop_density"].apply(classify)
    return df
