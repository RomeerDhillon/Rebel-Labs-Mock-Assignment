"use client";

import { useState } from "react";
import predictions from "@/lib/predictions";
import CountyMap from "@/components/CountyMap";
import CountyTable from "@/components/CountyTable";

type ViewMode = "map" | "table";

export default function CountiesPage() {
  const [view, setView] = useState<ViewMode>("map");

  const rCount = predictions.filter((p) => p.predicted_margin_r > 0).length;
  const dCount = predictions.length - rCount;

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <h1 className="text-3xl font-bold tracking-tight">
            County Predictions
          </h1>
          <p className="mt-1 text-gray-500">
            Projected margins for all 100 NC counties &mdash;{" "}
            <span className="font-semibold text-red-600">{rCount} R</span>
            {" / "}
            <span className="font-semibold text-blue-600">{dCount} D</span>
          </p>
        </div>

        {/* View Toggle */}
        <div className="inline-flex rounded-lg border border-gray-200 bg-white p-1 shadow-sm">
          <ToggleButton active={view === "map"} onClick={() => setView("map")}>
            <MapIcon />
            Map
          </ToggleButton>
          <ToggleButton
            active={view === "table"}
            onClick={() => setView("table")}
          >
            <TableIcon />
            Table
          </ToggleButton>
        </div>
      </div>

      {/* Content */}
      {view === "map" ? <CountyMap /> : <CountyTable />}
    </div>
  );
}

function ToggleButton({
  active,
  onClick,
  children,
}: {
  active: boolean;
  onClick: () => void;
  children: React.ReactNode;
}) {
  return (
    <button
      onClick={onClick}
      className={`inline-flex items-center gap-1.5 rounded-md px-4 py-2 text-sm font-medium transition-all ${
        active
          ? "bg-gray-900 text-white shadow-sm"
          : "text-gray-500 hover:bg-gray-50 hover:text-gray-700"
      }`}
    >
      {children}
    </button>
  );
}

